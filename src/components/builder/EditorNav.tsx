interface Props {
  activeSection: EditorSection;
  onSelect: (section: EditorSection) => void;
  resume: Resume;
}

export function EditorNav({ activeSection, onSelect, resume }: Props) {
  return (
    <nav className="rb-editor-nav" aria-label="Resume sections">
      <ul className="rb-editor-nav__list" role="list">
        {NAV_ITEMS.map((item) => {
          const count = item.count?.(resume);
          const isActive = activeSection === item.id;
          return (
            <li key={item.id}>
              <button
                type="button"
                className={`rb-editor-nav__item${isActive ? " rb-editor-nav__item--active" : ""}`}
                onClick={() => onSelect(item.id)}
                aria-current={isActive ? "page" : undefined}
              >
                <span className="rb-editor-nav__icon">{item.icon}</span>
                <span className="rb-editor-nav__label">{item.label}</span>
                {count !== undefined && count > 0 && (
                  <span className="rb-editor-nav__count" aria-label={`${count} items`}>
                    {count}
                  </span>
                )}
              </button>
            </li>
          );
        })}
      </ul>
    </nav>
  );
}
